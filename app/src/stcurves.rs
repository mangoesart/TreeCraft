/// The preset (index into CURVE_PRESETS) a new curve of this kind starts as: 0 Parent, 2 the
/// second curve. Spine:Noise:Late:Amount's second curve starts as Linear growth so the base of a
/// branch stays smooth (the person's request, picture 41; the original's definition doesn't
/// write one).
pub fn default_curve(name: &str, kind: u8) -> Option<usize> {
    if kind == 2 && name == "Spine:Noise:Late:Amount" {
        return Some(3);
    }
    let (_, p, s) = DEFAULT_CURVES.iter().find(|d| d.0 == name)?;
    let v = if kind == 0 { *p } else { *s };
    (v > 1).then(|| (v - 1) as usize)
}
