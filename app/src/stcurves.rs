/// Which curve buttons a property shows: [Parent, (unused), second curve]. The second curve
/// (0x01) works along the node's own length, as the original's radius and gravity curves do
/// (picture 36: "adjusting the curve does not make sense" with it read across siblings).
pub fn curve_kinds(name: &str, spline: bool) -> [bool; 3] {
    match CURVE_FLAGS.iter().find(|(n, _)| *n == name) {
        Some((_, f)) => [f & 2 != 0, false, f & 1 != 0],
        None => [spline, false, false],
    }
}

/// The second curve's colour: yellow when 0x04 is set (as on Lightmap:Weight), blue otherwise (as on
/// Season:Time scale).
pub fn second_is_yellow(name: &str) -> bool {
    CURVE_FLAGS.iter().find(|(n, _)| *n == name).map_or(true, |(_, f)| f & 4 != 0)
}

/// Whether a number property has the +/- (variance) button: the variance flag, or any curve (the
/// original shows +/- on every row with a curve box).
pub fn has_variance(name: &str, spline: bool) -> bool {
    match CURVE_FLAGS.iter().find(|(n, _)| *n == name) {
        Some((_, f)) => f & 0x13 != 0,
        None => spline,
    }
}
